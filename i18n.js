let currentLang=localStorage.getItem('sw-lang')||'zh';
function t(key){return (I18N[currentLang]&&I18N[currentLang][key])||I18N.zh[key]||key;}
function setLang(l){
  if(!I18N[l])return;
  currentLang=l;
  localStorage.setItem('sw-lang',l);
  document.body.className='lang-'+l;
  applyI18N();
  if(typeof renderList==='function')renderList();
  if(typeof renderGenUI==='function')renderGenUI();
  document.querySelectorAll('#langSwitch button').forEach(b=>b.classList.toggle('active',b.dataset.lang===l));
}
function applyI18N(){
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const k=el.getAttribute('data-i18n');
    el.textContent=t(k);
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el=>{
    const k=el.getAttribute('data-i18n-ph');
    el.placeholder=t(k);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el=>{
    const k=el.getAttribute('data-i18n-title');
    el.title=t(k);
  });
}